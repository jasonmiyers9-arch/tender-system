import type { TenderDetail } from '@/lib/api/types';
import type { ScrapedTender } from './tenderScraper';

// Builds a self-contained, single-binary PDF describing a tender so a company can
// download "what the tender is about" even when no original source PDF is attached.
// Mirrors the dependency-free PDF assembly used by complianceBundlePdf.ts.

const FULL_TEXT_LIMIT = 24000;

function normalizeText(value: string): string {
  return value
    .replace(/[–—]/g, '-')
    .replace(/[™]/g, '(TM)')
    .replace(/[‘’]/g, "'")
    .replace(/[“”]/g, '"')
    .replace(/[•]/g, '-')
    .replace(/[^\x20-\x7E]/g, '');
}

function escapePdfText(value: string): string {
  return normalizeText(value).replace(/\\/g, '\\\\').replace(/\(/g, '\\(').replace(/\)/g, '\\)');
}

function formatDate(value: string | null | undefined): string {
  if (!value) return 'N/A';
  const date = new Date(value);
  if (Number.isNaN(date.getTime())) return value;
  return date.toISOString().slice(0, 10);
}

function wrapLine(line: string, maxLength = 92): string[] {
  const words = normalizeText(line).split(/\s+/).filter(Boolean);
  const lines: string[] = [];
  let current = '';

  for (const word of words) {
    const next = current ? `${current} ${word}` : word;
    if (next.length > maxLength && current) {
      lines.push(current);
      current = word;
    } else {
      current = next;
    }
  }

  if (current) lines.push(current);
  return lines.length ? lines : [''];
}

function buildLines(tender: TenderDetail, scraped: ScrapedTender | null): string[] {
  const raw: string[] = [
    'Tender Document Summary',
    'Prepared by Tender Guard Pro(TM)',
    `Generated: ${formatDate(new Date().toISOString())}`,
    '',
    tender.title || 'Untitled tender',
    '',
    'Overview',
  ];

  const reference = tender.tenderNumber || scraped?.referenceNumber;
  if (reference) raw.push(`Reference: ${reference}`);
  raw.push(`Department / Organ of State: ${tender.organization || 'N/A'}`);
  raw.push(`Category: ${tender.category || 'N/A'}`);
  if (tender.tenderType) raw.push(`Tender type: ${tender.tenderType}`);
  if (tender.province) raw.push(`Province: ${tender.province}`);
  raw.push(`Required / delivery at: ${tender.requiredAt || tender.location || 'N/A'}`);
  raw.push(`Estimated value: ${tender.value || 'Not specified'}`);
  if (tender.advertised) raw.push(`Advertised: ${formatDate(tender.advertised)}`);
  raw.push(`Closing date: ${formatDate(tender.deadline)}${tender.closingTime ? ` at ${tender.closingTime}` : ''}`);

  if (tender.briefing?.hasBriefingSession) {
    raw.push(
      `Briefing session: ${tender.briefing.date || 'Date TBC'}${tender.briefing.venue ? `, ${tender.briefing.venue}` : ''}` +
        `${tender.briefing.isCompulsory ? ' (compulsory)' : ''}`,
    );
  }

  if (tender.description) {
    raw.push('', 'Description');
    raw.push(tender.description);
  }

  if (tender.requirements?.length) {
    raw.push('', 'Requirements');
    for (const item of tender.requirements) raw.push(`- ${item}`);
  }

  if (tender.eligibilityCriteria?.length) {
    raw.push('', 'Eligibility Criteria');
    for (const item of tender.eligibilityCriteria) raw.push(`- ${item}`);
  }

  if (tender.specialConditions) {
    raw.push('', 'Special Conditions');
    raw.push(tender.specialConditions);
  }

  const requiredDocs = Array.from(
    new Set([...(tender.required_categories ?? []), ...(tender.recommendedDocuments ?? [])].filter(Boolean)),
  );
  if (requiredDocs.length) {
    raw.push('', 'Documents You Will Likely Need');
    for (const item of requiredDocs) raw.push(`- ${item}`);
  }

  if (tender.contact && (tender.contact.contactPerson || tender.contact.email || tender.contact.telephone)) {
    raw.push('', 'Contact');
    if (tender.contact.contactPerson) raw.push(`Person: ${tender.contact.contactPerson}`);
    if (tender.contact.email) raw.push(`Email: ${tender.contact.email}`);
    if (tender.contact.telephone) raw.push(`Telephone: ${tender.contact.telephone}`);
  }

  if (scraped?.documents?.length) {
    raw.push('', 'Original Tender Documents');
    for (const doc of scraped.documents) {
      raw.push(`- ${doc.filename}${doc.url ? ` (${doc.url})` : ''}`);
    }
  }

  if (tender.sourceUrl) {
    raw.push('', 'Source');
    raw.push(`${tender.sourceSite ? `${tender.sourceSite}: ` : ''}${tender.sourceUrl}`);
  }

  const fullText = (scraped?.fullText || '').trim();
  if (fullText) {
    raw.push('', 'Full Tender Text (extracted from source documents)');
    raw.push(fullText.length > FULL_TEXT_LIMIT ? `${fullText.slice(0, FULL_TEXT_LIMIT)}\n[...truncated...]` : fullText);
  }

  raw.push('', 'Generated by Tender Guard Pro for informational purposes. Always confirm details against the official tender documents on the source portal before submitting.');

  return raw.flatMap((line) => wrapLine(line));
}

function pageContent(lines: string[], pageNumber: number, totalPages: number): string {
  const commands: string[] = ['BT', '/F1 10 Tf', '50 790 Td', '14 TL'];

  lines.forEach((line, index) => {
    if (index > 0) commands.push('T*');
    commands.push(`(${escapePdfText(line)}) Tj`);
  });

  commands.push(
    'ET',
    'BT',
    '/F1 8 Tf',
    '50 32 Td',
    `(Tender Guard Pro\\(TM\\) - Page ${pageNumber} of ${totalPages}) Tj`,
    'ET',
  );

  return commands.join('\n');
}

export function generateTenderDocumentPdf(tender: TenderDetail, scraped: ScrapedTender | null): Buffer {
  const allLines = buildLines(tender, scraped);
  const linesPerPage = 50;
  const pageLines: string[][] = [];
  for (let i = 0; i < allLines.length; i += linesPerPage) {
    pageLines.push(allLines.slice(i, i + linesPerPage));
  }
  if (pageLines.length === 0) pageLines.push(['No tender details available.']);

  const objects: string[] = [];
  objects.push('<< /Type /Catalog /Pages 2 0 R >>');

  const pageObjectNumbers = pageLines.map((_, index) => 3 + index * 2);
  objects.push(`<< /Type /Pages /Kids [${pageObjectNumbers.map((num) => `${num} 0 R`).join(' ')}] /Count ${pageLines.length} >>`);

  pageLines.forEach((lines, index) => {
    const pageObjectNumber = 3 + index * 2;
    const contentObjectNumber = pageObjectNumber + 1;
    const content = pageContent(lines, index + 1, pageLines.length);
    objects.push(`<< /Type /Page /Parent 2 0 R /MediaBox [0 0 612 842] /Resources << /Font << /F1 << /Type /Font /Subtype /Type1 /BaseFont /Helvetica >> >> >> /Contents ${contentObjectNumber} 0 R >>`);
    objects.push(`<< /Length ${Buffer.byteLength(content, 'latin1')} >>\nstream\n${content}\nendstream`);
  });

  const chunks: string[] = ['%PDF-1.4\n'];
  const offsets: number[] = [0];
  let offset = Buffer.byteLength(chunks[0], 'latin1');

  objects.forEach((object, index) => {
    offsets.push(offset);
    const chunk = `${index + 1} 0 obj\n${object}\nendobj\n`;
    chunks.push(chunk);
    offset += Buffer.byteLength(chunk, 'latin1');
  });

  const xrefOffset = offset;
  const xref = [
    `xref\n0 ${objects.length + 1}`,
    '0000000000 65535 f ',
    ...offsets.slice(1).map((item) => `${item.toString().padStart(10, '0')} 00000 n `),
    `trailer\n<< /Size ${objects.length + 1} /Root 1 0 R >>`,
    `startxref\n${xrefOffset}`,
    '%%EOF',
  ].join('\n');

  chunks.push(xref);
  return Buffer.from(chunks.join(''), 'latin1');
}

export function tenderDocumentFilename(tender: TenderDetail): string {
  const base = (tender.tenderNumber || tender.title || 'tender')
    .replace(/[^a-z0-9]+/gi, '-')
    .replace(/^-+|-+$/g, '')
    .slice(0, 60) || 'tender';
  return `${base}.pdf`;
}
